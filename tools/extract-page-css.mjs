// Extracts an admin-console page <style> block from its origin capture and
// scopes every selector under that page's body class, following the convention
// used by ExamView / ControlView. Idempotent: re-running rebuilds the target
// stylesheet from the capture.
//
//   node tools/extract-page-css.mjs ca     -> src/styles/ca-page.css
//   node tools/extract-page-css.mjs ict    -> src/styles/ict-page.css
//   node tools/extract-page-css.mjs comm   -> src/styles/comm-page.css
//   node tools/extract-page-css.mjs admin  -> src/styles/admin-page.css
//
// /admin/ started as tools/extract-admin-css.mjs; this is the same logic with
// the page as an argument. See D-33 for the two scoping corrections: unscoped
// html/body rules inside a media query are kept (anchored to the entry body's
// full class list so they out-specify enterprise.css's base rule), and the
// duplicate-selector dedupe only runs at the top level so a media override that
// repeats a top-level selector survives in cascade order.
import fs from 'node:fs';

const ROOT = 'C:/Users/USER/Documents/laaec-audit';

const PAGES = {
  admin: { file: 'admin.html', out: 'admin-page.css', scope: 'page-admin' },
  ca: { file: 'ca.html', out: 'ca-page.css', scope: 'page-ca' },
  ict: { file: 'ict.html', out: 'ict-page.css', scope: 'page-ict' },
  comm: { file: 'comm.html', out: 'comm-page.css', scope: 'page-comm' },
};

const page = process.argv[2] || 'admin';
const spec = PAGES[page];
if (!spec) {
  throw new Error(`unknown page "${page}" — expected one of ${Object.keys(PAGES).join(', ')}`);
}

const SRC = `${ROOT}/origin-pages/${spec.file}`;
const OUT = `${ROOT}/src/styles/${spec.out}`;
const SCOPE = `.${spec.scope}`;
// The entry <body> carries both classes (e.g. <body class="surface-enterprise
// page-ca">). Media-query body overrides have to out-specify enterprise.css's
// `body.surface-enterprise` base rule, which is a separate, later-injected
// stylesheet in this build, so they are anchored to both classes.
const BODY_SCOPE = `body.surface-enterprise.${spec.scope}`;

const html = fs.readFileSync(SRC, 'utf8');
const start = html.indexOf('<style>');
const end = html.indexOf('</style>', start);
if (start < 0 || end < 0) throw new Error('style block not found');
const css = html.slice(start + '<style>'.length, end);
const firstLine = html.slice(0, start).split('\n').length;
const lastLine = html.slice(0, end).split('\n').length;

/** Split a stylesheet into top-level chunks, keeping at-rules intact. */
const splitTopLevel = (source) => {
  const out = [];
  let depth = 0;
  let buf = '';
  for (const ch of source) {
    buf += ch;
    if (ch === '{') depth++;
    else if (ch === '}') {
      depth--;
      if (depth === 0) {
        out.push(buf.trim());
        buf = '';
      }
    }
  }
  if (buf.trim()) out.push(buf.trim());
  return out;
};

const HEADER = `/*
 * ${spec.out} — the /${page}/ page stylesheet.
 *
 * GENERATED by tools/extract-page-css.mjs from origin-pages/${spec.file}
 * (lines ${firstLine + 1}–${lastLine}) and re-scoped under ${SCOPE} so it cannot
 * leak into the other consoles. Tokens and the body rule live in
 * enterprise.css; the origin's own /admin-sidebar.css,
 * /exam-session-controls.css and /dashboard-registration.css are still served
 * as first-party files (D-03) and linked from the entry.
 *
 * Do not hand-edit: re-run the generator instead.
 */
`;

const chunks = splitTopLevel(css);
const seen = new Set();
const body = chunks
  .map((chunk) => {
    if (chunk.startsWith('@keyframes') || chunk.startsWith('@media') || chunk.startsWith('@supports')) {
      // at-rule: recurse into the inner rules for media queries
      if (chunk.startsWith('@media') || chunk.startsWith('@supports')) {
        const braceEnd = chunk.indexOf('{');
        const prelude = chunk.slice(0, braceEnd).trim();
        const inner = chunk.slice(braceEnd + 1, chunk.lastIndexOf('}'));
        // Inside a media query the unscoped body/html overrides are NOT
        // duplicated by enterprise.css — the <=900px block that switches the
        // body to `display: block` and releases `.main-content` lives only
        // here, so it has to be kept (scoped to this page's body class).
        const nested = splitTopLevel(inner)
          .map((r) => scopeRule(r, true, prelude))
          .join('\n\n');
        return `${prelude} {\n${nested}\n}`;
      }
      return chunk; // @keyframes untouched
    }
    return scopeRule(chunk);
  })
  .filter(Boolean)
  .join('\n\n');

function scopeRule(rule, inMedia = false, context = 'top') {
  const braceEnd = rule.indexOf('{');
  if (braceEnd < 0) return rule;
  const prelude = rule.slice(0, braceEnd).trim();
  const decls = rule.slice(braceEnd + 1, rule.lastIndexOf('}'));
  if (prelude === ':root') return ''; // tokens live in enterprise.css
  const scoped = prelude
    .split(',')
    .map((sel) => {
      const s = sel.trim();
      if (!s) return '';
      if (s.startsWith('@')) return s;
      if (inMedia) {
        // `html` cannot take a class, so anchor it to this page's body.
        if (s === 'html') return `html:has(${BODY_SCOPE})`;
        if (s === 'body') return BODY_SCOPE;
        if (s === 'html, body') {
          return `html:has(${BODY_SCOPE}),\n${BODY_SCOPE}`;
        }
        if (s === 'body::before' || s === 'body::after') {
          return `${BODY_SCOPE}${s.slice(4)}`;
        }
      }
      // html/body basics and the body surface rule are provided by
      // enterprise.css with identical declarations — drop the duplicates so
      // nothing unscoped can leak out of this file.
      if (s === 'html' || s === 'body' || s === 'html, body' || s === 'body::before' || s === 'body::after') {
        return '';
      }
      if (s.startsWith('body.')) return `body.${SCOPE.slice(1)} ${s.slice(5)}`;
      if (s.includes(',')) return s;
      return `${SCOPE} ${s}`;
    })
    .filter(Boolean)
    .join(',\n');
  if (!scoped) return '';
  // Dedupe only the top level: a media override that repeats a top-level
  // selector (the <=900px `.main-content` release) must survive, and so must a
  // later rule that overrides an earlier one inside the same media block, so
  // the origin's cascade is reproduced in order.
  if (!inMedia) {
    if (seen.has(scoped)) return '';
    seen.add(scoped);
  }
  return `${scoped} {\n${decls}\n}`;
}

fs.writeFileSync(OUT, `${HEADER}\n${body}\n`, 'utf8');
console.log(
  `wrote ${OUT} · ${body.split('\n').length} lines · ${chunks.length} source rules`,
);
